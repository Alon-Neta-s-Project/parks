/**
 * האם השאלה מבקשת שנבחר עבור מי ששואל.
 *
 * ⚠️ **אותו אוצר מילים כמו `src/lib/ask-intent.ts`, ובכוונה.** שתי
 * רשימות מילים בשני צדדים היו נעשות שונות תוך שבוע, ואז אותה שאלה
 * הייתה מסווגת אחרת בדפדפן ובשרת — בלי שאיש ישים לב.
 *
 * ⚠️ ומילת עובדה גוברת: "כמה זמן כדאי לתכנן ל-Everest" היא שאלה שיש לה
 * תשובה בטבלה, ושורות מועמדים עליה הן רעש.
 */
/**
 * כתיבה ליומן התשובות. **נכשלת בשקט, בכוונה.**
 *
 * ⚠️ `EdgeRuntime.waitUntil` כשהוא קיים — הוא מאפשר לבקשה להסתיים בלי
 * לחכות לכתיבה. כשאינו קיים, המתנה **חסומה בזמן**: שנייה אחת ולא יותר.
 * בלי הגבול הזה מסד איטי היה הופך לעיכוב על המסך של משפחה.
 */
function logTurn(
  url: string,
  key: string,
  t: {
    question: string;
    answered: boolean;
    reason: string | null;
    model: string;
    usage: { input?: number; output?: number } | null;
  },
): void {
  const write = fetch(`${url}/rest/v1/rpc/log_turn`, {
    method: "POST",
    headers: {
      apikey: key,
      Authorization: `Bearer ${key}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      p_question: t.question,
      p_answered: t.answered,
      p_refusal_reason: t.reason,
      p_model: t.model,
      p_input_tokens: t.usage?.input ?? null,
      p_output_tokens: t.usage?.output ?? null,
    }),
    signal: AbortSignal.timeout(1000),
  }).catch(() => {});

  const rt = (globalThis as { EdgeRuntime?: { waitUntil?: (p: Promise<unknown>) => void } })
    .EdgeRuntime;
  if (typeof rt?.waitUntil === "function") rt.waitUntil(write);
}

export function wantsRecommendation(q: string): boolean {
  const t = q.trim().toLowerCase();
  if (!t) return false;
  if (/(גובה|מגבלת|ס"מ|בחילה|מרטיב|כמה זמן|נגיש|ממוזג|תור|דילוג|פאס)/.test(t)) return false;
  if (/(תכנן|תכננו|לתכנן|מסלול|המלצ|תמליץ|תמליצו|מה לעשות)/.test(t)) return true;
  if (/(מה\s+דעת|מה\s+עדיף|איז[הו]\s.{0,40}?\s?(מתאימ|עדיפ))/.test(t)) return true;
  return /(מעדיפ|אוהב|מחפשים|מחפש|בא לנו)/.test(t)
    && /(פארק|פארקים|מתקנים|אטרקציות|רכבות|מופעים|חופשה|טיול)/.test(t);
}

/**
 * שורות המועמדים, בלי סינון עוצמה — הסינון הוא של המודל.
 *
 * ⚠️ **העוצמה נאמרת על כל שורה**, כי בלעדיה המודל אינו יכול לכבד את
 * "לא אוהבים אקסטרים מדי", וזה כל מה שהשורות האלה נועדו לאפשר.
 */
export function formatCandidates(rows: ParkCandidate[]): string {
  if (!rows.length) return "";
  const byPark = new Map<string, ParkCandidate[]>();
  for (const r of rows) {
    const list = byPark.get(r.park) ?? [];
    list.push(r);
    byPark.set(r.park, list);
  }
  const blocks = [...byPark].map(([park, list]) => {
    const items = list.map((r) => {
      const he = r.name_he ? ` (${r.name_he})` : "";
      const power = r.intensity === null ? "עוצמה לא דורגה" : `עוצמה ${r.intensity} מתוך 4`;
      const wet = r.gets_wet === "may_get_soaked" ? " · עלול להרטיב מאוד"
        : r.gets_wet === "may_get_wet" ? " · עלול להרטיב" : "";
      const h = r.height_cm ? ` · גובה מינימום ${r.height_cm} ס"מ` : "";
      return `  · ${r.name}${he} — ${power}${h}${wet}`;
    });
    return `${park}:\n${items.join("\n")}`;
  });
  return `[מועמדים לפי פארק — לבחירה לפי מה שנאמר, ולא להצגה כרשימה]\n${blocks.join("\n\n")}`;
}

export function formatExperiences(rows: ExperienceRow[]): string {
  const wet: Record<string, string> = {
    none: "לא מרטיב",
    may_get_wet: "עלול להרטיב",
    may_get_soaked: "עלול להרטיב מאוד",
    na: "לא רלוונטי — זה מופע",
  };
  const skip: Record<string, string> = {
    multi_pass: "כלול ב-Multi Pass",
    single_pass: "דורש Single Pass בתשלום נפרד",
    express: "זמין ב-Express Pass",
    none: "אין מוצר דילוג בתור",
  };
  return rows
    .map((r) => {
      const bits: string[] = [];
      // 🔴 **התקרה, והיא ההפך מהרצפה.** חמישה אזורי מים לפעוטות מגבילים
      // גובה כלפי מעלה. כל עוד היה כאן רק "גובה מינימום", אותו מספר נאמר
      // בכיוון ההפוך: "מגבלת הגובה בטייקס פיק היא 122" שלחה ילדה בגובה
      // 130 למתקן שלא ייתן לה לעלות, ולא הזהירה נער בגובה 160.
      //
      // ⚠️ ונאמר במילים ולא במספר לבדו. "122" ליד "גובה מינימום" ו-"122"
      // ליד "גובה מקסימלי" נראים דומים מדי במשפט אחד, והמודל הוא זה
      // שמנסח. המילה "עד" עושה את ההבדל.
      if (r.max_height_cm !== null && r.max_height_cm !== undefined) {
        bits.push(`⚠️ גובה מקסימלי: עד ${r.max_height_cm} ס"מ בלבד — מי שגבוה יותר אינו יכול לעלות`);
      }
      // 🔴 **התקרה נאמרת לפני הרצפה, ולא אחריה.**
      //
      // נטע שאלה על Bay Slides, וטים פתח ב"מגבלת הגובה לא נבדקה" —
      // נכון עובדתית, ומטעה כסדר. יש לנו תקרה מדודה של 152 ס"מ; מה
      // שחסר הוא הרצפה. משפט שנפתח בחסר קורא כ"אין לנו מידע", ומשפחה
      // שמקבלת אותו לא מגיעה בכלל לנתון שכן יש.
      //
      // ⚠️ מה שידוע נאמר ראשון. מה שחסר נאמר אחריו, ובמפורש.
      //
      // ⚠️ ושלושת המצבים של הרצפה נשמרים, ולעולם לא "0 ס\"מ".
      bits.push(
        // ⚠️ **ובצעד הבא, לא כסירוב יבש.** "לא נבדקה" נכון ועוצר את
        // הקוראת: היא יודעת שאין לנו, ולא מה לעשות עם זה. עיקרון פולה
        // מ-07.09 — "לא לנחש, אבל גם לא סירוב יבש, ותמיד להשאיר צעד
        // בא ברור" — נכתב על לוח זמנים משתנה, וחל כאן באותה מידה.
        // 🔴 **"אנחנו לא בדקנו" הוא דיווח על עצמנו, לא תשובה למשפחה.**
        //
        // נטע: "מה זה אנחנו לא בדקנו? ניסוח נוראי". היא צודקת — הנוסח
        // הזה מספר לקוראת על שיעורי הבית שלנו במקום לומר לה מה המצב.
        //
        // ⚠️ **ו"לא ידוע" לבדו היה גרוע יותר**, כי הוא נקרא כ"לא ידוע
        // על מגבלה" — כלומר היתר. "לא ידוע **אם קיימת**" אומר במדויק
        // מה שאינו ידוע: עצם קיומה. זה ההבדל בין נתון חסר לבין אישור.
        r.height_cm === null
          ? "מגבלת גובה מינימלית: לא ידוע אם קיימת · כדאי לבדוק בשילוט בכניסה למתקן"
          : r.height_cm === 0
          ? "אין מגבלת גובה מינימלית"
          : `גובה מינימום: ${r.height_cm} ס"מ`,
      );
      if (r.fits === true) bits.push("מתאים לגובה שנמסר");
      if (r.fits === false) bits.push("לא מתאים לגובה שנמסר");
      // ⚠️ fits === null אינו נאמר כ"מתאים". הוא פשוט לא נאמר.
      if (r.intensity !== null) bits.push(`עוצמה ${r.intensity} מתוך 4`);
      else bits.push("עוצמה: לא דורגה");
      // ── ארבעת דגלי הרגישות ──────────────────────────────────────────
      //
      // 🔴 עד 039 הם לא נשלחו כלל, וטים אמר "אין לי מידע לגבי רמת החשיכה"
      // על מתקן שהעמודה שלו מלאה. הנתון נאסף, נבדק, אוחסן — ולא הוצג.
      //
      // ⚠️ **שלושה מצבים לכל דגל, ו-`null` נאמר במפורש.** דגל שלא נבדק
      // ודגל שנבדק ואין בו רגישות נראים זהים אם שותקים על שניהם, ומשפחה
      // שקוראת רשימה נקייה מניחה שהיא נקייה. זה הכלל שכל הפרויקט בנוי
      // סביבו, וכאן הוא נוגע לילד עם רגישות לאור.
      const sens: [string, string | null | undefined][] = [
        ["חושך או מקומות סגורים", r.sens_dark],
        ["גבהים", r.sens_heights],
        ["רעש חזק או פתאומי", r.sens_loud],
        ["הבזקי אור", r.sens_strobe],
      ];
      // 🔴 **הרגרסיה הרביעית מאותה תבנית, ונטע תפסה גם אותה.**
      //
      // הגרסה הקודמת פלטה שורה על `true`, על `null` ועל `"na"` — ועל
      // `"false"` שתקה. אז טים ענה "אין לי את הנתון לגבי רגישות לחושך
      // במתקן Buzz Lightyear" על עמודה שכתוב בה במפורש `false`: נבדק,
      // ואין. הנתון הכי מרגיע שיש לנו הוא היחיד שלא הגיע אליו.
      //
      // ⚠️ **ולכן אין יותר רשימות מותנות.** ארבעת הדגלים נאמרים תמיד,
      // כל אחד עם מצבו, בשורה אחת. מבנה שבו מצב מסוים אינו מיוצג הוא
      // מבנה שאפשר לשכוח בו מצב — וזה קרה כאן שלוש פעמים ברצף (`na`,
      // `status_note`, ועכשיו `false`). כשכל מצב חייב מילה, אין שתיקה
      // שהמודל יכול לפרש.
      const sensWord: Record<string, string> = {
        "true": "כן",
        "false": "נבדק — אין",
        na: "לא רלוונטי",
      };
      // ⚠️ `undefined` — מסד בלי 039 — אינו "לא נבדק". הוא נתון שלא הגיע,
      // ואמירה עליו היא המצאה. הוא נופל מהרשימה לגמרי.
      const sensSaid: string[] = [];
      for (const [k, v] of sens) {
        if (v === undefined) continue;
        sensSaid.push(`${k}: ${v === null ? "לא נבדק" : sensWord[v] ?? v}`);
      }
      if (sensSaid.length) bits.push(`רגישויות — ${sensSaid.join(" · ")}`);
      if (r.gets_wet) bits.push(wet[r.gets_wet] ?? r.gets_wet);
      if (r.skip_line) bits.push(skip[r.skip_line] ?? r.skip_line);
      else bits.push("מוצר דילוג בתור: לא נבדק");
      if (r.status !== "open") {
        // ⚠️ ארבעה סטטוסים, ולא משפט אחד לשלושה מהם.
        //
        // קודם כל מה שאינו open נאמר כ"אינו פתוח כרגע", וזו טענה חדה
        // יותר ממה שהנתון מחזיק. temporarily_closed על Meet Moana הוא
        // הכרעת פולה שמשמעותה "אי אפשר לסמוך על נוכחות הדמות" — ומשפחה
        // שקוראת "אינו פתוח כרגע" מוחקת את המפגש מהיום, כשייתכן מאוד
        // שהוא פועל.
        //
        // זו אותה תבנית שנתפסה כאן שוב ושוב, בכיוון ההפוך: ערך שמשמעותו
        // "לא ידוע / משתנה" נקרא כערך חד. הפעם הוא לא הבטיח בטיחות אלא
        // שלל אפשרות, וזה מזיק באותה מידה.
        // 🔴 **אוצר המילים כאן אינו זה שמגיע.** הייבוא פולט שלושה ערכים
        // בלבד — open · closed · check — ו-temporarily_closed ו-coming_soon
        // אינם נוצרים על ידו לעולם. כלומר ניסוח פולה מ-07.09 יושב כאן
        // ומעולם לא הגיע למסך, ואילו `check` נפל לענף ברירת המחדל והוצג
        // למשתמשת כ"⚠️ סטטוס: check" — מילה באנגלית בממשק עברי.
        //
        // ⚠️ זו בדיוק האזהרה שכתובה במיגרציה 037: שינוי אוצר מילים מחייב
        // שינוי בשני הצדדים. שם היא נכתבה כדי למנוע את זה, וכאן זה כבר קרה.
        // `check` נוסף עכשיו; איחוד מלא של השלושה מול השניים ממתין לפולה,
        // כי הניסוח שלה הוא הכרעת מוצר ולא באג.
        const say: Record<string, string> = {
          closed: "⚠️ סגור",
          // ניסוח פולה, 08.09. ⚠️ **תג קבוע וקצר, ובלי לפצל לשני ערכים.**
          // הפרוזה ב-status_note מחזיקה את הפרטים והיא שונה מאוד בין שורה
          // לשורה ("צפוי להיפתח ב-14 בספטמבר" מול "לוח זמנים משתנה"), וטים
          // כבר מבדיל ביניהן נכון בניסוח שלו. תג אחד שאינו מכריע לאיזה
          // מהמצבים מדובר, ומשאיר את ההבחנה למשפט — ולא לשינוי סכמה.
          check: "⚠️ יש לוודא לפני ההגעה.",
          // ⚠️ ניסוח פולה, 07.09. "אינו בלוח קבוע" עדיין נשמע כמו העדר;
          // זה אינו "לא קורה" אלא "משתנה, תבדקו בפועל" — אותו עיקרון
          // שהוכרע היום על שעת המצעד: לא לנחש, אבל גם לא סירוב יבש,
          // ותמיד להשאיר צעד־בא ברור.
          temporarily_closed:
            "⚠️ מתקיים בהתאם ללוח זמנים משתנה — מומלץ לבדוק באפליקציה או באתר הרשמי ביום הביקור",
          coming_soon: "⚠️ טרם נפתח",
        };
        // ערך שאינו במפה אינו נופל לברירת מחדל שקטה: הוא נאמר כפי שהוא,
        // כדי שסטטוס חדש ייראה ולא ייבלע.
        const label = say[r.status] ?? `⚠️ סטטוס: ${r.status}`;
        bits.push(`${label}${r.status_note ? ` — ${r.status_note}` : ""}`);
      } else if (r.status_note) {
        // 🔴 **הערת סטטוס על שורה פתוחה — וזו רגרסיה שיצרתי אתמול.**
        //
        // עד אתמול 19 מתקני Volcano Bay היו מסומנים "סגור" בטעות, וההערה
        // שלהם — "Planned park maintenance closure begins Oct 26, 2026" —
        // הגיעה לטים דרך ענף הסטטוס הסגור. תיקנתי את הסיווג ל"פתוח",
        // **וההערה נעלמה יחד איתו**, כי הענף הזה רץ רק על מה שאינו פתוח.
        //
        // ⚠️ נטע שאלה "האם קראקטאו פתוח", וטים ענה "פתוח" בלי לומר מילה
        // על סגירת התחזוקה. משפחה שמתכננת לסוף אוקטובר לא הייתה יודעת.
        //
        // ⚠️ ומה שזה מלמד: **תיקון של סיווג שגוי אינו מסתיים בסיווג.**
        // המידע שנתלה עליו נוסע איתו, וכשהוא זז — הוא נופל.
        //
        // ⚠️ והניסוח כאן שונה מזה שלמעלה בכוונה: השורה **פתוחה**, וכל תג
        // אזהרה היה סותר את זה. זו הערה על העתיד, לא על היום.
        bits.push(`פתוח · לתשומת לב: ${r.status_note}`);
      }
      const he = r.name_he ? ` (${r.name_he})` : "";
      // 🔴 **אזור ריק כאן אינו "לא ידוע", והשתיקה עליו נקראה ככה.**
      //
      // נטע שאלה "באיזה אזור נמצאים JAMMitors", וטים ענה "המידע לגבי
      // האזור הספציפי אינו מופיע אצלי" — כי `land` הגיע `null` והשורה
      // פשוט לא נכתבה. אבל הנתון **קיים ונבדק**: במאסטר כתוב `N/A`,
      // ופירושו שללהקה אין מקום קבוע. אמרנו "אין לנו" על תשובה שיש.
      //
      // ⚠️ ומה שמאפשר לומר את זה בביטחון: במאסטר אין ולו שדה Area ריק
      // אחד — 234 אמיתיים, 8 `N/A`, אפס ריקים. בונה הזרע עוצר מהיום על
      // ריק, ולכן `null` כאן יכול להגיע רק מ-`N/A`.
      //
      // "משתנה" — הכרעת פולה, 09.09.
      // 🔴 **"משתנה" היה מילה אחת על שני מצבים שונים, ונטע תפסה את זה.**
      //
      // הכרעת פולה מ-09.09 הייתה "משתנה", ואני העברתי לה — ולפיליפ —
      // שמדובר בשמונה **אמנים נודדים**. בדקתי את השורות בפועל, וזה לא
      // נכון: ארבע מהן הן מפגשי דמויות שהמקום שלהן כתוב בשם עצמו
      // (Adventurers Outpost · Character Landing · Discovery Island ·
      // Zoogether Day Gathering Spot). הן אינן משתנות בכלל.
      //
      // ⚠️ ומה שמשותף לכל השמונה הוא צר בהרבה: **הן אינן משויכות ל-land
      // מוגדר בפארק.** זה מה שהעמודה מודדת, וזה כל מה שאפשר לומר בלי
      // לנחש. "משתנה" הבטיח ידיעה על ההתנהגות שלהן שאין לנו.
      //
      // ⚠️ זו אותה תבנית בכיוון ההפוך: קודם מצב אחד נבלע בשתיקה, וכאן
      // מילה אחת נמרחה על מצבים שונים. בשני המקרים המבנה טען יותר
      // ממה שהנתון מחזיק.
      const where = !r.land || r.land === "N/A"
        ? " · אינו משויך לאזור מוגדר בפארק"
        : ` · ${r.land}`;
      const when = r.last_verified ? ` · נבדק ${r.last_verified}` : "";
      return `[מתקן: ${r.name}${he} · ${r.park}${where}${when}]\n${bits.join(" · ")}`;
    })
    .join("\n\n");
}

/** קטע כפי שהוא חוזר מ-match_knowledge. */
export interface KnowledgeChunk {
  content: string;
  volatility: string | null;
  last_verified: string | null;
  /**
   * ⚠️ **נשלף ולא נזרק.** `match_knowledge` מחזירה אותו מאז 028, והוא
   * נבלע כאן — כלומר שישה ממקרי סט הזהב שדורשים `must_cite_tier: [T1]`
   * לא היו ניתנים לבדיקה כלל: אין במה להסתכל.
   *
   * הוא **אינו** נכנס להקשר של המודל. הוא יוצא בתשובה כדי שבדיקה תוכל
   * לוודא מאיזו דרגת מקור נשענה התשובה — קטע T1 הוא מקור רשמי, ותשובה
   * שנשענת רק על דרגה נמוכה יותר היא ממצא ולא תקלה.
   */
  authority_tier: string | null;
}

/**
 * הקטעים, כפי שהם נכנסים להקשר של המודל.
 *
 * ⚠️ **הסימון מגיע מ-volatility ולא מהטקסט.** זה כל הרעיון של סעיף 8:
 * פסקת סייג בגוף כל מסמך הייתה מקרבת את כל המסמכים זה לזה במרחב
 * ה-embedding — ככל שהשאלה כללית יותר כך משקלה של הפסקה המשותפת גדל —
 * וגם כופלת מידע שכבר קיים כשדה. כאן הוא נכתב פעם אחת, לכל קטע, מהשדה.
 *
 * ⚠️ ובלי מקורות. match_knowledge אינה מחזירה source_urls, ומה שאינו
 * מגיע לכאן אינו יכול לדלוף לתשובה.
 */
/**
 * 🔴 **מה שאסור לצאת — נחסם בקוד, ולא בהוראה.**
 *
 * ההוראות אומרות לטים לא לחשוף קישורים ומפתחות. הוראה היא בקשה: מודל
 * יכול לא לציית לה, ו-prompt injection הוא בדיוק הניסיון לגרום לכך.
 * **מה שחייב להיות ודאי נבדק על הפלט**, אחרי שהמודל סיים.
 *
 * ⚠️ **וזו שכבה אחרונה ולא ראשונה.** ההגנה האמיתית היא שמה שאסור לחשוף
 * **אינו נמצא בהקשר מלכתחילה**: מפתחות נשלחים ככותרת HTTP ואינם בפרומפט,
 * ו-`match_knowledge` אינה מחזירה `source_url` כלל. אי אפשר לחלץ מה
 * שלא נשלח. הפונקציה הזו תופסת את מה שבכל זאת הצליח להיווצר.
 */
export function scrubAnswer(text: string): { clean: string; hits: string[] } {
  const hits: string[] = [];
  let clean = text;

  // כתובת אתר. טים אמור לומר "באתר הרשמי", ולעולם לא לצטט כתובת.
  clean = clean.replace(/https?:\/\/\S+|\b[a-z0-9-]+\.(com|org|net|co\.il)\/\S*/gi, () => {
    hits.push("url");
    return "באתר הרשמי";
  });

  // חומר שנראה כמו מפתח. אינו אמור להתקיים בהקשר — ואם הופיע, לא יוצא.
  clean = clean.replace(
    /AIza[0-9A-Za-z_-]{20,}|eyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}|sb_(secret|publishable)_[A-Za-z0-9]{16,}/g,
    () => {
      hits.push("key");
      return "";
    },
  );

  return { clean, hits };
}

export function formatChunks(chunks: KnowledgeChunk[]): string {
  const mark: Record<string, string> = {
    volatile: "משתנה",
    seasonal: "עונתי",
    static: "יציב",
  };
  return chunks
    .map((c, i) => {
      // ⚠️ volatility חסר אינו "יציב". קטע בלי סימון נאמר בזהירות ולא
      // בביטחון — ברירת המחדל היא לכיוון הבטוח, לא לכיוון הנוח.
      const tag = c.volatility ? mark[c.volatility] ?? "משתנה" : "משתנה";
      const when = c.last_verified ? ` · נבדק ${c.last_verified}` : "";
      return `[קטע ${i + 1} · ${tag}${when}]\n${c.content}`;
    })
    .join("\n\n");
}

