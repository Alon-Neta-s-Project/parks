/**
 * שאלות דעה — הרחבה שאושרה על ידי פולה, 08.09.
 *
 * 🔴 **שני הבאגים שדווחו נפלו בדיוק כאן.** אוצר המילים הקודם היה בנוי סביב
 * **פעלים** — "תכנן", "תמליץ", "עזרו לי" — ושני המשפטים שפיליפ דיווח עליהם
 * אינם פקודות אלא שאלות דעה:
 *
 *   "חשבנו 3 ימי דיסני + יומיים יוניברסל, מה דעתך?"
 *   "איזה פארק מתאים לזוג בני 30"
 *
 * שניהם נפלו ל"לא ברור" והמשיכו לטים כרגיל.
 *
 * ⚠️ **ו"מתאים ל" לבדו אינו כאן, בכוונה.** נטע שאלה "האם באז לייטיר מתאים
 * לילד שמפחד מחושך" — שאלה **עובדתית** על מתקן שמות, שעברה בבדיקה שלה.
 * ביטוי "מתאים ל" חשוף היה הופך אותה לשאלת בירור ושובר תשובה שעובדת.
 *
 * מה שמפריד: **"איזה X מתאים" הוא בקשה לבחור בשבילנו. "האם X מתאים" הוא
 * שאלה על X.** הראשון דורש להכיר את המשפחה, השני לא.
 */
export const OPINION: RegExp[] = [
  /מה\s+דעת(ך|כם|כן)/,
  /מה\s+(אתה|אתם|את)\s+(חושב|חושבים|חושבת)/,
  /מה\s+עדיף/,
  /איז[הו]\s.{0,40}?\s?מתאימ?[הים]?\s*ל/,
  /איז[הו]\s.{0,40}?\s?עדיפ?[הים]?/,
  /what\s+do\s+you\s+think/i,
];

/**
 * האם השאלה מבקשת שנבחר עבור מי ששואל.
 *
 * ⚠️ **מילת עובדה גוברת.** "כמה זמן כדאי לתכנן ל-Everest" מזכירה תכנון
 * ויש לה תשובה מהטבלה; שאלת בירור עליה היא התחמקות ולא שירות.
 *
 * ⚠️ **ומה שנשאר בחוץ, בכוונה: "לא ברור".** ההוראה שאושרה מדברת על שאלת
 * בירור "כשלא ברור מה נשאל", אבל ניתוב **כל** מה שאינו מזוהה לשאלת בירור
 * היה שובר שאלות שעובדות היום — למשל "כמה עולה כרטיס יומי למג'יק
 * קינגדום", שאין בה מילת עובדה מהרשימה ואין בה מילת תכנון, ושטים עונה
 * עליה נכון היום ("אין לי מחירים"). היא הייתה מקבלת "שלוש שאלות קצרות
 * קודם" על שאלה שיש לה תשובה.
 *
 * לכן: **רק בקשה מפורשת לתכנן או לבחור.** כל השאר ממשיך לטים, שכבר יודע
 * לומר "אין לי את זה". מדווח לפיליפ ולפולה.
 */
export function asksUsToChoose(text: string): boolean {
  const q = text.trim().toLowerCase();
  if (!q) return false;
  if (FACT_WORDS.some((w) => q.includes(w))) return false;
  return PLANNING.some((w) => q.includes(w)) || OPINION.some((re) => re.test(q));
}
