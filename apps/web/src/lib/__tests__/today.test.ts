import { describe, expect, it } from "vitest";
import { todayLine } from "../../../../../supabase/functions/tim/index";

/**
 * 🔴 נולדה מכשל אמיתי במסך חי, 08.09.
 *
 * טים אמר שמתקן "ייפתח ב-24 באוגוסט 2026" — תאריך שכבר עבר. הוא לא קרא
 * לא נכון; הוא לא ידע מה היום. שום מקום בפונקציה לא מסר לו את זה.
 */
describe("התאריך שנמסר לטים", () => {
  it("נמסר, ובפורמט שניתן להשוואה", () => {
    expect(todayLine(new Date("2026-09-08T13:00:00Z"))).toContain("2026-09-08");
  });

  /**
   * ⚠️ השרת ב-UTC והפארקים בפלורידה. ב-01:00 UTC באורלנדו עדיין אתמול,
   * ותשובה לפי UTC הייתה מזיזה את היום קדימה — יום שלם של הבדל על השאלה
   * "האם המתקן פתוח היום".
   */
  it("שעון אורלנדו, לא UTC", () => {
    // 2026-09-09 בשעה 01:00 UTC = 2026-09-08 בשעה 21:00 באורלנדו
    expect(todayLine(new Date("2026-09-09T01:00:00Z"))).toContain("2026-09-08");
    expect(todayLine(new Date("2026-09-09T01:00:00Z"))).not.toContain("2026-09-09");
  });

  /**
   * ⚠️ מחושב בכל קריאה. קבוע ברמת המודול היה נקבע בהתעוררות הפונקציה
   * ונשאר תקוע שם — אותה תבנית של "התוכן השתנה וההצהרה נשארה", רק
   * שההצהרה כאן היא התאריך עצמו.
   */
  it("שתי קריאות בימים שונים מחזירות ימים שונים", () => {
    expect(todayLine(new Date("2026-09-08T13:00:00Z")))
      .not.toBe(todayLine(new Date("2026-09-09T13:00:00Z")));
  });

  it("ההוראה עצמה נאמרת, ולא רק המספר", () => {
    const line = todayLine(new Date("2026-09-08T13:00:00Z"));
    expect(line).toContain("אינו אירוע עתידי");
  });
});
