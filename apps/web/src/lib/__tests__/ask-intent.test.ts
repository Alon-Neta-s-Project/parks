import { describe, expect, it } from "vitest";
import { asksUsToChoose, shouldAskUpFront } from "../ask-intent";

/**
 * הבדיקה נכתבה מהמקרים האמיתיים של היום — שני הבאגים שפיליפ דיווח עליהם,
 * ותשע השאלות שעברו אצל נטע. שתי הרשימות חשובות באותה מידה: הראשונה היא
 * מה שצריך להשתנות, השנייה היא מה שאסור שיישבר בדרך.
 */
describe("מתי טים נשאל, ומתי הוא שואל", () => {
  /**
   * 🔴 שני המשפטים שדווחו. שניהם נפלו קודם ל"לא ברור" והמשיכו לטים כרגיל,
   * כי אוצר המילים היה בנוי סביב פעלים ולא סביב שאלות דעה.
   */
  it("שאלת דעה מזוהה — שני המשפטים של פיליפ", () => {
    expect(asksUsToChoose(
      "מגיעים לאורלנדו ל-5 ימים, חשבנו 3 ימי דיסני + יומיים יוניברסל, מה דעתך?",
    )).toBe(true);
    expect(asksUsToChoose("איזה פארק מתאים לזוג בני 30")).toBe(true);
  });

  it("בקשת תכנון מפורשת מזוהה", () => {
    for (const q of ["תכננו לי יום", "עזרו לי לתכנן טיול", "plan me a day", "תמליץ על מסלול"]) {
      expect(asksUsToChoose(q), q).toBe(true);
    }
  });

  /**
   * 🔴 הבדיקה החשובה יותר: תשע השאלות שעברו אצל נטע חייבות להמשיך לעבור.
   *
   * ⚠️ במיוחד "האם באז לייטיר מתאים לילד שמפחד מחושך" — היא מכילה
   * "מתאים ל", והיא שאלה **עובדתית** על מתקן שמות. ביטוי "מתאים ל" חשוף
   * ברשימת שאלות הדעה היה הופך אותה לשאלת בירור ושובר תשובה שעובדת.
   */
  it("שאלות שעברו בבדיקה של נטע ממשיכות ישר לטים", () => {
    for (const q of [
      "מה מגבלת הגובה באקספדישן אוורסט?",
      "מה מגבלת הגובה בדה אינקרדיבל האלק קוסטר?",
      "מה מגבלת הגובה בדמבו דה פליינג אלפנט?",
      "האם ג'וראסיק פארק ריבר אדוונצ'ר פתוח?",
      "מתי נפתח דה מג'יק אוף דיסני אנימיישן?",
      "האם קראקטאו אקווה קוסטר פתוח?",
      "מתי אפשר להזמין Lightning Lane Multi Pass?",
      "האם באז לייטיירס ספייס ריינג'ר ספין מתאים לילד שמפחד מחושך?",
      "יש מתקן בשם ספייס ריינג'ר תלת ממד?",
      "כמה עולה כרטיס יומי למג'יק קינגדום?",
      "האם הדאפר דנס מפחיד למי שפוחד מגבהים?",
    ]) {
      expect(asksUsToChoose(q), q).toBe(false);
    }
  });

  /**
   * ⚠️ מילת עובדה גוברת על מילת תכנון. לשאלה הזו יש תשובה בטבלה, ושאלת
   * בירור עליה היא התחמקות ולא שירות.
   */
  it("מילת עובדה גוברת על מילת תכנון", () => {
    expect(asksUsToChoose("כמה זמן כדאי לתכנן לאקספדישן אוורסט?")).toBe(false);
  });

  /**
   * 🔴 השאלה שפולה דיווחה עליה, 09.09 — הצהרת העדפה בלי פועל שאלה.
   *
   * טים ענה עליה עם Downhill Double Dipper: מגלשה בעוצמה 4/4 בפארק מים,
   * והסביר למה היא לא מתאימה למי שכתב "לא אוהבים אקסטרים מדי". שלוש
   * שגיאות במשפט אחד — פארק מים, עוצמה הפוכה, והובלה בשלילה.
   */
  it("הצהרת העדפה רחבה היא בקשת המלצה", () => {
    for (const q of [
      "מעדיפים פארקים עם תפאורה יפה ומתקנים כיפיים אבל לא אוהבים אקסטרים מדי",
      "אנחנו מחפשים פארק רגוע למשפחה",
      "אוהבים מופעים יותר מרכבות",
    ]) {
      expect(asksUsToChoose(q), q).toBe(true);
    }
  });

  /**
   * ⚠️ והגבול: הצהרה על **מתקן אחד שמות** אינה בקשה שנבחר עבור מי שכתב.
   * פועל העדפה לבדו היה בולע אותה, ולכן נדרשת גם מילת היקף רחב.
   */
  it("העדפה על מתקן בודד אינה בקשת המלצה", () => {
    expect(asksUsToChoose("אנחנו אוהבים את באז לייטיר")).toBe(false);
    expect(asksUsToChoose("אוהבים את Hagrid's")).toBe(false);
  });

  /**
   * 🔴 **שאלת הבירור נשאלה גם באמצע שיחה שכבר ענתה עליה.**
   *
   * נטע שתלה את השאלה בכוונה באמצע צ'אט מלא — משפחה עם ילדים בני 5
   * ו-7, ארבעה ימי פארקים, עולמות דיסני והארי פוטר — כדי לראות אם טים
   * ממשיך או מתחיל מחדש. הוא התחיל מחדש, **ובלי שנשאל בכלל**: המסך
   * עצר לפניו והציג את שאלות הפתיחה.
   *
   * ⚠️ אותה תבנית שחזרה כאן כל היום — כלל נכון שהוחל בלי תנאי.
   */
  it("שאלת בירור רק בתחילת שיחה, לא באמצעה", () => {
    const q = "מעדיפים פארקים עם תפאורה יפה ומתקנים כיפיים";
    expect(shouldAskUpFront(q, false)).toBe(true);
    expect(shouldAskUpFront(q, true)).toBe(false);
  });

  it("טקסט ריק אינו בקשה", () => {
    expect(asksUsToChoose("   ")).toBe(false);
  });
});
